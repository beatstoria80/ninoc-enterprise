-- ============================================================
-- Add is_auto_reply to support_messages table
-- ============================================================

-- Add the column if it doesn't exist
ALTER TABLE support_messages
ADD COLUMN IF NOT EXISTS is_auto_reply BOOLEAN DEFAULT false;

-- Update existing rows to false (they're all manual)
UPDATE support_messages
SET is_auto_reply = false
WHERE is_auto_reply IS NULL;

-- Add a comment for documentation
COMMENT ON COLUMN support_messages.is_auto_reply IS 'True if this message was auto-generated by the auto-reply system';

